

unique() para saber quantos e quais elementos existem em um data frame
extenso. 

aggregate() formula usada para descobrir características estatísticas
(média, moda, sd, max, min...) de uma coluna específica de um dataframe

merge() usado para fundir dois dataframes em um só. é melhor usado se 
houver uma coluna em comum entre os dois, como 'id'. Bem fácil de usar.

sub() para substituir palavras por outras em dataframes. bem fácil de 
usar e útil. 